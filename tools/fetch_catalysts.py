def classify(title):
    """把标题分成 政策 / 产业 / 公司；纯行情播报、纯数据发布、空谈返回 None。

    顺序很重要，四条闸逐层收窄：

    ① 纯数据发布：光有部委名 + 一组统计数字不算政策。
       「国家医保局：近三年公立医院种植牙手术年均增长率71%」曾拿到最高分 ——
       它确实出自医保局，但只是统计数字，没有任何政策动作。
    ② 空谈：讨论会 / 据悉 / 或将于。「欧洲理事会就芯片法案2.0举行政策讨论会」
       只因为带了「政策」两个字就拿到全板块最高分，这类不构成可交易变化。
    ③ 个股公告：`公司名：动作` 的格式要先于政策判定 —— 否则
       「利扬芯片：调整定增方案」会被「方案」二字判成政策。
    ④ 纯行情播报：「午评：沪指窄幅震荡半日涨0.27%，生物制品、CRO概念、创新药
       板块涨幅居前」里有「生物制品」，但它只是播报，不是上涨的原因 ——
       这正是用户明确要剔除的那类内容。
    """
    t = title or ""
    # ⓪ 收评/午评/盘面播报：整条就是行情复盘，**无条件剔除**。
    # 「A股收评：创业板指探底回升跌0.49%，兵装重组概念、元件板块表现活跃」曾靠
    # 「重组」二字过了下面所有闸、当上元件板块的主因 —— 它恰恰是用户点名不要的那类。
    if any(w in t for w in ["收评", "午评", "早盘播报", "盘中播报", "收盘播报",
                            "盘面播报", "收盘快评", "两市播报"]):
        return None
    hard = any(w in t for w in HARD_POLICY)
    if any(w in t for w in DATA_ONLY) and not hard:
        return None
    if any(w in t for w in VAGUE) and not any(w in t for w in HARD_CORE):
        return None
    if any(w in t for w in NEGATIVE):
        return None                                   # 利空/否定，不能解释上涨
    if any(w in t for w in MACRO_MKT) and not any(w in t for w in IND_EVENT):
        return None                                   # 宏观/外盘，不是行业催化
    if any(w in t for w in FOREIGN_VOICE) and is_overseas(t):
        return None                                   # 海外官员表态，驱动不了 A 股板块
    if any(w in t for w in LOW_VALUE) and not hard:
        return "公司"                                 # 流程性报道，最低权重
    # 大宗商品价格是**因**，不是「板块拉升」那种**果**：
    # 「现货黄金突破4190美元/盎司」对贵金属板块就是当天最直接的驱动。
    # 所以带价位的商品价格异动单独放行。
    # ⚠️ 两步都必须放在 QUOTE_ONLY 分支**外面**：「首创期货：金银反弹，现货黄金重返
    # 4300美元」不含任何播报词，走不到那个分支，结果一条金价异动被整条丢掉。
    # 而 `"板块" not in t` 是必须的：放宽之后「贵金属板块短线拉升，湖南黄金涨超8%」
    # 立刻靠「黄金 + 8」挤进来当了主因 —— 那正是用户点名不要的盘中播报。
    if "板块" not in t and "概念" not in t and any(w in t for w in COMMODITY):
        if any(w in t for w in PRICE_FLASH):
            return "产业"
        if any(w in t for w in PRICE_UNIT) and any(w in t for w in PRICE_VERB):
            return "产业"
    m = re.match(r"^([^：:]{2,14})[：:]", t)
    if m and not any(w in m.group(1) for w in GOV_PREFIX) \
            and any(w in t for w in CO_ACTIONS):
        return "公司"
    pol_hits = [w for w in POLICY_BODY if w in t]
    ind_hit = any(w in t for w in IND_EVENT)
    if not pol_hits and not ind_hit and any(w in t for w in QUOTE_ONLY):
        return None                                   # 纯播报（商品价格异动上面已放行）
    # 政策判定：必须命中**强锚点**。
    # 只命中弱词（方案/试点/标准/核准…）时：
    #   · 标题里还有产业动作词 → 按产业算（重卡换电试点项目 / 产品方案）
    #   · 标题是「解决方案」这类产品说法 → 按产业算
    #   · 其余（如「国家标准10月1日起实施」）仍算政策
    if pol_hits:
        if any(w not in POLICY_WEAK for w in pol_hits):
            return "政策"
        if any(w in t for w in POLICY_FAKE):
            return "产业"
        if not ind_hit:
            return "政策"
    if ind_hit:
        return "产业"
    if any(w in t for w in CO_EVENT):
        return "公司"
    return None


_ASCII_KW = re.compile(r"^[A-Za-z0-9]+$")


def kw_in(t, k):
    """关键词匹配。纯 ASCII 的关键词（IP / 5G / DRAM / LME…）必须按词边界匹配。

    起因：「巴西央行调查显示，经济学家预计2026年巴西官方IPCA通胀指数年率将达4.99%」
    靠 "IPCA" 里的 "IP" 命中了传媒组（IP 是传媒的定义性关键词），拿了 s=9 当上主因 ——
    一条巴西通胀新闻成了文化传媒的催化。子串匹配对拉丁缩写就是灾难。
    """
    if _ASCII_KW.match(k):
        return re.search(r"(?<![A-Za-z0-9])" + re.escape(k) + r"(?![A-Za-z0-9])", t) is not None
    return k in t


# 领跌侧的「栏目噪音」比领涨侧少一项：公告/股东减持/问询函/立案调查
# 在下跌语境里**恰恰是**要找的东西，不能当噪音剔掉。
TITLE_NOISE_DOWN = [w for w in TITLE_NOISE if w not in (
    "公告", "股东减持", "监管工作函", "问询函", "关注函", "警示函", "立案调查", "异动")]


def classify_down(title):
    """把标题归到「导致下跌」的五个维度之一；没有明确利空信号返回 None。

    与 classify() 是镜像关系，但**不能合并**：
      · classify() 第一件事就是杀掉所有负面词（它要解释「涨」）；
      · 这里反过来，**必须**命中一条负面信号才承认它是催化。
    命中不到 → 界面标注「技术性回调 / 资金轮动」，不硬凑。

    维度顺序也有讲究：资金面先判（这类标题常带「板块」二字，容易被播报闸误杀），
    龙头个股的「公司名：动作」形态要在泛基本面之前判，否则
    「宁德时代：三季度净利同比下滑」会被泛泛的「业绩」归类吃掉。
    """
    t = title or ""
    # 收评/午评/盘面播报：整条是行情复盘，无条件剔除
    if any(w in t for w in ["收评", "午评", "早盘播报", "盘中播报", "收盘播报",
                            "盘面播报", "收盘快评", "两市播报"]):
        return None
    if any(w in t for w in TITLE_NOISE_DOWN):
        return None
    # 否认/辟谣：「公司：没有减持计划」不是利空
    if any(w in t for w in BEAR_DENY):
        return None
    # 海外官员表态：驱动不了 A 股板块（和领涨侧同一个判据）
    if any(w in t for w in FOREIGN_VOICE) and is_overseas(t):
        return None
    # 纯数据发布：是「描述过去」，不是「驱动未来」（和领涨侧同一个判据）。
    # 「交通运输部：上周港口吞吐量27878.1万吨，环比下降1.36%」就是典型 —— 周度读数
    # 不构成下跌原因。但带硬利空（预亏/处罚/制裁…）的算事件，见 BEAR_EXEMPT。
    if any(w in t for w in DATA_ONLY) and not any(w in t for w in BEAR_EXEMPT):
        return None
    # 结果播报：「半导体板块跌超5%」「XX概念跌幅居前」——是跌本身，不是跌的原因
    if re.search(r"(板块|概念)[^，。；、]{0,12}(跌|跌停|大跌|下挫|跳水|走弱|"
                 r"领跌|跌幅居前|杀跌|回落|低迷)", t):
        return None
    if any(w in t for w in DOWN_QUOTE):
        return None

    # ④ 资金流向与估值压力
    if any(w in t for w in BEAR_FLOW):
        return "资金估值"
    # ① 政策与监管变化
    if any(w in t for w in BEAR_POLICY):
        return "政策监管"
    # ③ 龙头个股负面事件（`公司名：动作` 形态优先于泛基本面）
    m = re.match(r"^([^：:]{2,14})[：:]", t)
    if m and not any(w in m.group(1) for w in GOV_PREFIX) \
            and any(w in t for w in BEAR_COMPANY):
        return "龙头个股"
    # ⑤ 海外或宏观扰动
    if any(w in t for w in BEAR_MACRO):
        return "海外宏观"
    # ③ 不带冒号的公司负面
    if any(w in t for w in BEAR_COMPANY):
        return "龙头个股"
    # ② 行业基本面与业绩预期
    if any(w in t for w in BEAR_FUND):
        return "基本面"
    return None


def persist_of(t, ty):
    """持续性判断：短期 / 中期 / 长期。

    先看标题里的显式时间限定词，没有才退回维度默认值。
    「暂停」「阶段性」这类词能救回一批被默认值判成中期的条目。
    """
    if any(w in t for w in PERSIST_LONG):
        return "长期"
    if any(w in t for w in PERSIST_SHORT):
        return "短期"
    return PERSIST_DEF.get(ty, "中期")


def dir_of(ty, direct, tag, down=True):
    """影响方向：利空 / 偏空（领涨侧对称地是 利好 / 偏多）。

    直接作用于该板块（板块名直路、官方板块标签，或政策/基本面/龙头这类硬因素）才说
    「利空」；只通过情绪、外盘、资金面传导的说「偏空」。
    不夸大 —— 一条「美股科技股大跌」对 A 股电子是**偏空**不是**利空**。
    """
    hard = direct or tag or ty in DIR_STRONG
    if down:
        return "利空" if hard else "偏空"
    return "利好" if hard else "偏多"


def is_overseas(t):
    """纯海外消息：出现外国主体、且没有任何国内主体。"""
    if not any(w in t for w in FOREIGN):
        return False
    return not any(w in t for w in CN_MARK)


