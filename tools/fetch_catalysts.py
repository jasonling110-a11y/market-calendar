def window_items(by_day, day, prev_day):
    """取出 [prev_day 15:00, day 15:00] 窗口内的条目。

    为什么必须卡窗口：反向检索捞回来的重磅消息时间戳普遍在 17:00~23:00，
    属于**收盘后** —— 只能驱动次日，不能解释当天上涨。不卡窗口就是把
    「明天的原因」安到「今天的涨幅」上。
    """
    rows = []
    for d, items in by_day.items():
        if d < prev_day or d > day:
            continue
        for it in items:
            hm = it["hm"]
            if d == prev_day:
                if hm < "15:00":
                    continue
            elif d == day:
                if hm >= "15:00":
                    continue
            rows.append(it)
    return rows


def similar(a, b):
    return difflib.SequenceMatcher(None, a, b).ratio()


